def eul_reul(word):
    """받침 있으면 '을', 없으면 '를' 반환"""
    last = word.strip()[-1]
    if "가" <= last <= "힣":
        return "을" if (ord(last) - ord("가")) % 28 != 0 else "를"
    return "를"


